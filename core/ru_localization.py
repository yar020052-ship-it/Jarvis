def translate(value):
    """Translate known English UI strings, leaving names and user data intact."""
    if not isinstance(value, str):
        return value
    translated = _TRANSLATIONS.get(value)
    if translated is not None:
        return translated
    for source, target in (("SYS: ", "СИСТЕМА: "), ("ERR: ", "ОШИБКА: "), ("INFO: ", "ИНФО: ")):
        if value.startswith(source):
            return target + value[len(source):]
    if value.startswith("SESSION "):
        return "СЕАНС " + value[len("SESSION "):]
    return value
