def audit() -> dict:
    """Describe the installed AI configuration and its measurable gaps."""
    data = catalog(force=True)
    observed = {key: set(value) for key, value in data["observed_ids"].items()}
    type_counts = data["types"]
    gaps: list[dict] = []
    recommendations: list[str] = []

    for kind in AUDIT_TYPES:
        if not type_counts.get(kind):
            gaps.append({
                "kind": kind,
                "severity": "high" if kind in {"air_factory_balance", "force_build_armies"} else "medium",
                "detail": f"no installed ai_strategy of type {kind}",
            })

    highlight = (
        ("equipment_production_factor", "fighter", "AI does not prioritise fighters"),
        ("equipment_production_factor", "cas", "AI does not prioritise close air support"),
        ("equipment_production_factor", "anti_air", "AI does not prioritise anti-air equipment"),
        ("equipment_production_factor", "anti_tank", "AI does not prioritise anti-tank equipment"),
        ("equipment_production_factor", "convoy", "AI does not prioritise convoys"),
        ("template_prio", "infantry", "no explicit infantry template priority"),
        ("template_prio", "armor", "no explicit armour template priority"),
    )
    coverage = data.get("country_coverage") or {}
    country_total = max(1, len(data.get("country_files") or []))
    threshold = max(2, country_total // 5)
    for kind, ident, detail in highlight:
        covered = int(coverage.get(f"{kind}:{ident}", 0) or 0)
        if covered < threshold:
            gaps.append({
                "kind": f"{kind}:{ident}",
                "severity": "medium",
                "detail": f"{detail} (explicit in {covered}/{country_total} country AI files)",
            })

    if not data["country_files"]:
        gaps.append({
            "kind": "country_specific_ai",
            "severity": "medium",
            "detail": "no per-country ai_strategy files found",
        })

    # Template/equipment coverage from the separate AI folders.
    roles = set(data.get("ai_template_roles") or [])
    for role in ("infantry", "armor", "garrison", "motorized"):
        if role not in roles:
            gaps.append({
                "kind": f"ai_templates:{role}",
                "severity": "low",
                "detail": f"no ai_templates role named {role}",
            })

    if not observed.get("research_weight_factor"):
        recommendations.append("Add research_weight_factor entries for core infantry/artillery/AA/AT technologies.")
    if not type_counts.get("air_factory_balance"):
        recommendations.append("Add air_factory_balance so the AI stops under-funding its air force.")
    if not observed.get("equipment_production_factor", set()) >= {"anti_air", "anti_tank"}:
        recommendations.append("Add AA/AT production weights; the default AI undervalues both.")
    if not observed.get("template_prio", set()):
        recommendations.append("Add template_prio entries to make the AI field better division compositions.")
    if not type_counts.get("garrison"):
        recommendations.append("Tune the garrison strategy to stop draining front divisions for occupation duty.")
    recommendations.append("Re-run the audit after every Millennium Dawn update and reinstall the package.")
    if gaps:
        targets = ", ".join(sorted({gap["kind"].split(":")[0] for gap in gaps}))
        recommendations.insert(0, f"The generated package targets these measured gaps: {targets}.")

    installed = status()
    return {
        "ok": True,
        "mods_root": data["mods_root"],
        "game_root": data["game_root"],
        "mod_root": data["mod_root"],
        "files": data["files"],
        "country_files": len(data["country_files"]),
        "type_counts": type_counts,
        "gaps": gaps,
        "recommendations": recommendations,
        "package": package_stats(data),
        "installed": installed,
    }


def render_audit(report: dict) -> str:
    lines = [
        "JARVIS AI Director — audit",
        f"  mods: {report.get('mods_root') or 'not found'}",
        f"  strategy files: {report.get('files', 0)} "
        f"({report.get('country_files', 0)} country-specific)",
        "",
        "Most used strategy types:",
    ]
    for kind, count in list((report.get("type_counts") or {}).items())[:12]:
        lines.append(f"  {kind}: {count}")
    lines.append("")
    lines.append("Gaps:")
    gaps = report.get("gaps") or []
    if not gaps:
        lines.append("  none found")
    for gap in gaps[:20]:
        lines.append(f"  [{gap['severity']}] {gap['kind']}: {gap['detail']}")
    lines.append("")
    lines.append("Recommendations:")
    for item in report.get("recommendations") or []:
        lines.append(f"  - {item}")
    stats = report.get("package") or {}
    lines.append("")
    lines.append(
        f"Package: {stats.get('blocks', 0)} blocks, {stats.get('entries', 0)} strategies, "
        f"{stats.get('dropped', 0)} dropped as unsupported."
    )
    installed = report.get("installed") or {}
    lines.append(f"Installed: {'yes' if installed.get('installed') else 'no'}")
    for warning in installed.get("warnings") or []:
        lines.append(f"  ! {warning}")
    return "\n".join(lines)


