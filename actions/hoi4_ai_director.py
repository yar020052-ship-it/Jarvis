def _roots() -> tuple[Path | None, Path | None]:
    from actions.hoi4_knowledge import discover_game_root, discover_mod_root

    return discover_game_root(), discover_mod_root()


def mods_dir() -> Path | None:
    """Return the user's HOI4 ``mod`` directory (next to Millennium Dawn)."""
    _game, mod_root = _roots()
    return mod_root.parent if mod_root else None


def install_dir() -> Path | None:
    base = mods_dir()
    return base / MOD_FOLDER if base else None


def descriptor_path() -> Path | None:
    base = mods_dir()
    return base / DESCRIPTOR_FILE if base else None


def strategy_path() -> Path | None:
    root = install_dir()
    return root / "common" / "ai_strategy" / STRATEGY_FILE if root else None


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return ""


def _matching_brace(text: str, open_at: int) -> int | None:
    from actions.hoi4_live_state import _matching_brace

    return _matching_brace(text, open_at)


def _scalar(text: str, key: str) -> str | None:
    # Works for both multi-line Paradox blocks and the compact one-line
    # ``ai_strategy = { type = ... id = ... value = ... }`` form.
    match = re.search(
        rf"(?im)(?:^|[\s{{]){re.escape(key)}\s*=\s*(?:\"([^\"]*)\"|([^\s#}}]+))", text
    )
    if not match:
        return None
    return (match.group(1) if match.group(1) is not None else match.group(2)).strip()


def _iter_strategy_blocks(text: str):
    """Yield ``(type, id, value)`` for each ``ai_strategy = { ... }`` line block."""
    for match in re.finditer(r"ai_strategy\s*=\s*\{([^{}]*)\}", text, re.S):
        body = match.group(1)
        kind = _scalar(body, "type")
        if not kind:
            continue
        ident = _scalar(body, "id")
        raw_value = _scalar(body, "value")
        try:
            value = float(raw_value) if raw_value is not None else None
        except ValueError:
            value = None
        yield kind, ident, value


def _source_strategy_files() -> list[Path]:
    """Base game plus MD strategy files, excluding our own generated file."""
    files: list[Path] = []
    game_root, mod_root = _roots()
    for root in (game_root, mod_root):
        if not root:
            continue
        folder = root / "common" / "ai_strategy"
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*.txt")):
            if path.name == STRATEGY_FILE:
                continue
            files.append(path)
    return files


def catalog(force: bool = False) -> dict:
    """Collect every ``type -> known ids`` pair used by the installed AI files."""
    game_root, mod_root = _roots()
    signature = []
    files = _source_strategy_files()
    for path in files:
        try:
            stat = path.stat()
        except OSError:
            continue
        signature.append((str(path), stat.st_size, stat.st_mtime_ns))
    key = hashlib.sha1(repr(signature).encode("utf-8", "replace")).hexdigest()
    if not force and _AUDIT_CACHE.get("signature") == key:
        return _AUDIT_CACHE["catalog"]  # type: ignore[return-value]

    observed: dict[str, set[str]] = {}
    type_counts: dict[str, int] = {}
    country_files: set[str] = set()
    country_coverage: dict[str, int] = {}
    for path in files:
        text = _read(path)
        if not text:
            continue
        name = path.stem
        is_country = bool(re.fullmatch(r"[A-Z]{3}", name))
        if is_country:
            country_files.add(name)
        for kind, ident, _value in _iter_strategy_blocks(text):
            type_counts[kind] = type_counts.get(kind, 0) + 1
            if ident:
                observed.setdefault(kind, set()).add(ident)
                if is_country:
                    key = f"{kind}:{ident}"
                    country_coverage[key] = country_coverage.get(key, 0) + 1

    buildings = _building_ids(game_root, mod_root)
    templates = _ai_template_roles(game_root, mod_root)
    equipment = _equipment_archetypes(game_root, mod_root)
    data = {
        "files": len(files),
        "country_files": sorted(country_files),
        "types": dict(sorted(type_counts.items(), key=lambda kv: -kv[1])),
        "observed_ids": {key: sorted(value) for key, value in observed.items()},
        "country_coverage": dict(sorted(country_coverage.items(), key=lambda kv: -kv[1])),
        "buildings": sorted(buildings),
        "ai_template_roles": sorted(templates),
        "equipment_archetypes": sorted(equipment),
        "game_root": str(game_root or ""),
        "mod_root": str(mod_root or ""),
        "mods_root": str(mods_dir() or ""),
    }
    _AUDIT_CACHE["signature"] = key
    _AUDIT_CACHE["catalog"] = data
    return data


def _building_ids(*roots) -> set[str]:
    found: set[str] = set()
    for root in roots:
        if not root:
            continue
        folder = root / "common" / "buildings"
        if not folder.is_dir():
            continue
        for path in folder.rglob("*.txt"):
            text = _read(path)
            for match in re.finditer(r"(?m)^\s*([A-Za-z0-9_]+)\s*=\s*\{", text):
                name = match.group(1)
                if name not in {"buildings", "shared_buildings"}:
                    found.add(name)
    return found


def _ai_template_roles(*roots) -> set[str]:
    found: set[str] = set()
    for root in roots:
        if not root:
            continue
        folder = root / "common" / "ai_templates"
        if not folder.is_dir():
            continue
        for path in folder.rglob("*.txt"):
            found.update(re.findall(r"(?m)^\s*role\s*=\s*([A-Za-z0-9_]+)", _read(path)))
            found.update(re.findall(r"(?m)^\s*([A-Za-z0-9_]+)\s*=\s*\{", _read(path)))
    found.discard("upgrade_prio")
    found.discard("target_template")
    return found


def _equipment_archetypes(*roots) -> set[str]:
    found: set[str] = set()
    for root in roots:
        if not root:
            continue
        folder = root / "common" / "units" / "equipment"
        if not folder.is_dir():
            continue
        for path in folder.rglob("*.txt"):
            text = _read(path)
            found.update(re.findall(r"(?m)^\s*archetype\s*=\s*([A-Za-z0-9_]+)", text))
            found.update(re.findall(r"(?m)^\s*([A-Za-z0-9_]+)\s*=\s*\{\s*$", text))
    return found


