def install(force: bool = False) -> dict:
    """Write the generated submod.  Returns a report dictionary."""
    root = install_dir()
    descriptor = descriptor_path()
    if not root or not descriptor:
        return {"ok": False, "error": "HOI4 mod directory not found (is Millennium Dawn installed?)"}
    target = root / "common" / "ai_strategy" / STRATEGY_FILE
    if root.exists():
        existing = _read(target)
        if existing and MARKER not in existing and not force:
            return {"ok": False, "error": f"{root} exists and is not managed by JARVIS; refusing to overwrite"}
        if root.exists() and not force and not existing:
            return {"ok": False, "error": f"{root} already exists; pass force=True to replace it"}
    text, stats = build_strategy()
    if stats["problems"]:
        return {"ok": False, "error": "generated file failed validation", "stats": stats}
    if not stats["entries"]:
        return {"ok": False, "error": "no package entry is supported by the installed AI files", "stats": stats}
    _write(target, text)
    _write(root / "descriptor.mod", _descriptor_text())
    _write(root / "README.txt", _readme_text(text))
    _write(descriptor, _descriptor_text())
    return {
        "ok": True,
        "path": str(target),
        "descriptor": str(descriptor),
        "stats": stats,
        "status": status(),
    }


def uninstall() -> dict:
    root = install_dir()
    descriptor = descriptor_path()
    if not root or not descriptor:
        return {"ok": False, "error": "HOI4 mod directory not found"}
    target = root / "common" / "ai_strategy" / STRATEGY_FILE
    removed: list[str] = []
    if target.exists():
        text = _read(target)
        if MARKER not in text:
            return {"ok": False, "error": f"{target} is not a JARVIS file; refusing to delete"}
        target.unlink()
        removed.append(str(target))
    readme = root / "README.txt"
    if readme.exists() and MARKER in _read(readme):
        readme.unlink()
        removed.append(str(readme))
    inner = root / "descriptor.mod"
    if inner.exists():
        inner.unlink()
        removed.append(str(inner))
    if descriptor.exists() and MOD_NAME in _read(descriptor):
        descriptor.unlink()
        removed.append(str(descriptor))
    # Remove now-empty directories, never touching foreign files.
    for folder in (target.parent, root / "common", root):
        try:
            folder.rmdir()
            removed.append(str(folder))
        except OSError:
            pass
    return {"ok": True, "removed": removed}


def status() -> dict:
    root = install_dir()
    descriptor = descriptor_path()
    target = strategy_path()
    report: dict = {
        "installed": bool(root and target and target.is_file()),
        "path": str(target) if target else "",
        "descriptor": str(descriptor) if descriptor else "",
        "warnings": [],
    }
    if not report["installed"]:
        return report
    text = _read(target)
    report["size"] = len(text.encode("utf-8"))
    report["sha1"] = hashlib.sha1(text.encode("utf-8")).hexdigest()
    report["marker"] = MARKER in text
    report["strategies"] = sum(1 for _ in _iter_strategy_blocks(text))
    if not report["marker"]:
        report["warnings"].append("installed file has no JARVIS marker")
    problems = validate_strategy_text(text)
    if problems:
        report["warnings"].extend(problems)
    if not descriptor or not descriptor.is_file():
        report["warnings"].append("launcher descriptor is missing")
    expected, stats = build_strategy()
    if expected.strip() != text.strip():
        report["warnings"].append("installed file is stale; run install(force=True)")
        report["stale"] = True
    else:
        report["stale"] = False
    report["stats"] = stats
    return report


