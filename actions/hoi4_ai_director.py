"""JARVIS AI Director: an additive AI-improvement submod for HOI4 / Millennium Dawn.

The in-game AI planner is compiled into ``hoi4.exe``; a mod cannot replace it.
It *can*, however, add ``common/ai_strategy`` blocks that change the weights the
planner uses.  This module audits the installed AI configuration, generates a
small, conservative, fully validated set of additive strategies, and installs
them as a separate ``JARVIS_AI_Director`` mod.  Millennium Dawn is never
modified: the generated mod is loaded after it and only adds one new file.

Safety rules:

* every ``type``/``id`` pair emitted is copied from an id that already occurs in
  the installed base-game or Millennium Dawn ``ai_strategy`` files;
* values stay in a small, conservative range;
* install refuses to overwrite a foreign mod folder;
* uninstall only removes files that carry the JARVIS marker.
"""

