def _id_supported(kind: str, ident: str, data: dict) -> bool:
    if not ident:
        return kind in VALUE_ONLY_TYPES
    known = set((data.get("observed_ids") or {}).get(kind) or [])
    if not known:
        return False
    return ident in known


def package_stats(data: dict | None = None) -> dict:
    data = data or catalog()
    entries = 0
    dropped = 0
    for block in PACKAGE.values():
        for kind, ident, _value in block["entries"]:
            if _id_supported(kind, ident, data):
                entries += 1
            else:
                dropped += 1
    return {"blocks": len(PACKAGE), "entries": entries, "dropped": dropped}


def build_strategy(data: dict | None = None) -> tuple[str, dict]:
    """Render the package using only ids that exist in the installed files."""
    data = data or catalog()
    lines = [
        MARKER,
        "# Additive AI weights only. Millennium Dawn files are not modified.",
        "# Every type/id pair below is validated against the installed AI scripts.",
        "# Delete this file (or the whole mod) to return to the original AI.",
        "",
    ]
    used: list[tuple[str, str, float]] = []
    dropped: list[str] = []
    for block_name, block in PACKAGE.items():
        accepted = []
        for kind, ident, value in block["entries"]:
            if _id_supported(kind, ident, data):
                accepted.append((kind, ident, value))
                used.append((kind, ident, value))
            else:
                dropped.append(f"{kind}:{ident or '<value>'}")
        if not accepted:
            continue
        lines.append(f"# {block['comment']}")
        lines.append(f"{block_name} = {{")
        lines.append("\tallowed = { always = yes }")
        enable = block.get("enable")
        if enable:
            lines.append(f"\tenable = {{ {enable} }}")
            lines.append("\tabort_when_not_enabled = yes")
        else:
            lines.append("\tenable = { always = yes }")
        lines.append("")
        for kind, ident, value in accepted:
            if ident:
                lines.append(f"\tai_strategy = {{ type = {kind} id = {ident} value = {value:g} }}")
            else:
                lines.append(f"\tai_strategy = {{ type = {kind} value = {value:g} }}")
        lines.append("}")
        lines.append("")
    text = "\n".join(lines).rstrip() + "\n"
    problems = validate_strategy_text(text, data)
    stats = {
        "blocks": sum(1 for name in PACKAGE if f"{name} = {{" in text),
        "entries": len(used),
        "dropped": len(dropped),
        "dropped_ids": dropped,
        "problems": problems,
    }
    return text, stats


