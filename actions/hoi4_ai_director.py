def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="hoi4_ai_director", description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("audit", help="show AI configuration gaps")
    sub.add_parser("status", help="show whether the director is installed")
    preview = sub.add_parser("preview", help="print the generated strategy file")
    preview.add_argument("--json", action="store_true", help="print stats as JSON")
    install_cmd = sub.add_parser("install", help="generate and install the submod")
    install_cmd.add_argument("--force", action="store_true", help="overwrite an existing JARVIS install")
    sub.add_parser("uninstall", help="remove the generated submod")
    args = parser.parse_args(argv)

    if args.command == "audit":
        print(render_audit(audit()))
        return 0
    if args.command == "status":
        print(json.dumps(status(), ensure_ascii=False, indent=2))
        return 0
    if args.command == "preview":
        text, stats = build_strategy()
        if args.json:
            print(json.dumps(stats, ensure_ascii=False, indent=2))
        else:
            print(text)
        return 0 if not stats["problems"] else 1
    if args.command == "install":
        result = install(force=args.force)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0 if result.get("ok") else 1
    if args.command == "uninstall":
        result = uninstall()
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0 if result.get("ok") else 1
    return 2


def _tool_handler(parameters: dict | None = None, player=None, **_kwargs) -> str:
    """JARVIS tool entry point: audit / status / install / uninstall."""
    action = str((parameters or {}).get("action", "status")).strip().lower()
    if action in {"audit", "analyse", "analyze"}:
        return render_audit(audit())
    if action == "status":
        report = status()
        if not report.get("installed"):
            return "AI Director не установлен. Действие audit покажет слабые места ИИ, install установит сабмод."
        text = (
            f"AI Director установлен: {report.get('strategies', 0)} стратегий, "
            f"{report.get('size', 0)} байт, актуален: {'нет' if report.get('stale') else 'да'}."
        )
        if report.get("warnings"):
            text += " Предупреждения: " + "; ".join(report["warnings"][:5])
        return text
    if action == "install":
        result = install(force=bool((parameters or {}).get("force")))
        if not result.get("ok"):
            return f"Не установил AI Director: {result.get('error')}"
        stats = result.get("stats") or {}
        return (
            f"AI Director установлен: {stats.get('blocks', 0)} блоков, "
            f"{stats.get('entries', 0)} стратегий. Включите JARVIS_AI_Director в лаунчере "
            "после Millennium Dawn. Файлы Millennium Dawn не изменялись."
        )
    if action == "uninstall":
        result = uninstall()
        if not result.get("ok"):
            return f"Не удалил AI Director: {result.get('error')}"
        return f"AI Director удалён; файлов удалено: {len(result.get('removed') or [])}."
    if action in {"preview", "generate"}:
        text, stats = build_strategy()
        if stats["problems"]:
            return "Сгенерированный файл не прошёл проверку: " + "; ".join(stats["problems"][:5])
        return text
    return "Неизвестное действие AI Director: используйте audit | status | install | uninstall | preview."


