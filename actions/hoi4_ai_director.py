def validate_strategy_text(text: str, data: dict | None = None) -> list[str]:
    """Return human-readable problems; an empty list means the file is safe."""
    data = data or catalog()
    observed = {key: set(value) for key, value in data.get("observed_ids", {}).items()}
    problems: list[str] = []
    if text.count("{") != text.count("}"):
        problems.append("unbalanced braces")
    for index, match in enumerate(re.finditer(r"ai_strategy\s*=\s*\{([^{}]*)\}", text, re.S)):
        body = match.group(1)
        kind = _scalar(body, "type")
        if not kind:
            problems.append(f"block {index}: missing type")
            continue
        if kind not in EMITTABLE_TYPES:
            problems.append(f"block {index}: type {kind} is not emittable by this module")
            continue
        ident = _scalar(body, "id")
        if kind in ID_TYPES:
            if not ident:
                problems.append(f"block {index}: type {kind} requires id")
                continue
            known = observed.get(kind, set())
            if known and ident not in known:
                problems.append(f"block {index}: id {ident} is not used by the installed {kind} strategies")
        elif ident is not None:
            problems.append(f"block {index}: type {kind} must not carry id")
        raw_value = _scalar(body, "value")
        if raw_value is None:
            problems.append(f"block {index}: missing value")
            continue
        try:
            value = float(raw_value)
        except ValueError:
            problems.append(f"block {index}: value {raw_value!r} is not numeric")
            continue
        if abs(value) > MAX_ABS_VALUE:
            problems.append(f"block {index}: value {value:g} exceeds the conservative limit {MAX_ABS_VALUE:g}")
    return problems


